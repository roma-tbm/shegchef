#: Сокращения для ключа --week: «пн», «вт», «ср», «чт», «пт».
WEEKDAY_SHORTCUTS: dict[str, str] = {
    "пн": "Понедельник",
    "пон": "Понедельник",
    "вт": "Вторник",
    "вторник": "Вторник",
    "ср": "Среда",
    "среда": "Среда",
    "чт": "Четверг",
    "чтв": "Четверг",
    "четверг": "Четверг",
    "пт": "Пятница",
    "пятница": "Пятница",
}


def normalize_weekday(value: str) -> str | None:
    """«пн», «ПН», «понедельник» или «1» → «Понедельник». Неизвестное — None."""
    text = value.strip().lower().replace(".", "")
    if not text:
        return None
    if text in WEEKDAY_SHORTCUTS:
        return WEEKDAY_SHORTCUTS[text]
    if text.isdigit():
        index = int(text)
        return WEEKDAYS[index - 1] if 1 <= index <= len(WEEKDAYS) else None
    for day in WEEKDAYS:
        if text == day.lower():
            return day
    return None


def plan_for(weekday: str) -> tuple[PlanLine, ...]:
    """Строки плана одного дня недели."""
    name = normalize_weekday(weekday)
    if name is None:
        raise ValueError(
            f"Неизвестный день недели: «{weekday}». Ожидается один из: "
            f"{', '.join(WEEKDAYS)} (или сокращение: пн, вт, ср, чт, пт)."
        )
    return tuple(p for p in WEEK_PLAN if p.weekday == name)


