"""Общая ошибка пользовательских хранилищ ShegChef.

Повреждённый или структурно неверный файл данных — это не «пусто»: молчаливое
чтение в пустой словарь позволяло бы следующему сохранению затереть содержимое.
CLI и веб ловят `StoreError`, показывают понятную ошибку и не меняют исходные
байты (AC06). Отсутствующего файла это не касается — это допустимое состояние.
"""

from __future__ import annotations


class StoreError(ValueError):
    """Хранилище нельзя прочитать или безопасно перезаписать."""


def corrupt_message(path, exc: Exception | None = None) -> str:
    """Единообразное сообщение о повреждённом хранилище с причиной."""
    reason = f": {exc}" if exc is not None else ""
    return (
        f"хранилище {path} повреждено{reason}. "
        "Исправьте или уберите файл вручную — данные не перезаписываются."
    )


__all__ = ["StoreError", "corrupt_message"]